import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, copyFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { PrismaLibSql } from '@prisma/adapter-libsql';
import { PrismaClient } from '../src/generated/prisma/client';
import { createCustomerAuth } from '../src/lib/customer-auth-core';
import { createManagedUser, createManagedPet, syncCustomer, createPetInvitation, acceptPetInvitation, tokenDigest, consumeCustomerLimit } from '../src/lib/customer-core';
const temp = mkdtempSync(join(tmpdir(), 'milo-accounts-'));
copyFileSync(resolve('prisma/dev.db'), join(temp, 'test.db'));
const db = new PrismaClient({ adapter: new PrismaLibSql({ url: 'file:' + join(temp, 'test.db') }) });
const mails: {to:string; text:string}[] = [];
const baseURL = 'http://localhost:3007';
const auth = createCustomerAuth(db, { secret: 'test-secret-only-in-throwaway-database-123456789', baseURL, mail: async mail => { mails.push(mail); } });
const person = (email:string) => ({ name:'Ana', lastName:'Pérez', phone:'+56912345678', email });
const password = 'Frase segura de prueba 2026';
async function call(path:string, body?:unknown, cookie?:string) {
 return auth.handler(new Request(baseURL + '/api/auth' + path, { method:body ? 'POST':'GET', headers:{ Origin:baseURL, "x-forwarded-for":"127.0.0.1", ...(body ? {'Content-Type':'application/json'}:{}), ...(cookie ? {Cookie:cookie}:{}) }, ...(body ? {body:JSON.stringify(body)}:{}) }));
}
after(async()=>{await db.$disconnect(); rmSync(temp,{recursive:true,force:true});});
test('registro verifica correo, cifra contraseña y revoca sesión al recuperarla', async()=>{
 const email='register@example.test';
 let response=await call('/sign-up/email',{...person(email),password, emailVerified:true,active:false});
 assert.equal(response.status,200,await response.text());
 let user=await db.user.findUniqueOrThrow({where:{email}});
 assert.equal(user.emailVerified,false); assert.equal(user.active,true);
 const account=await db.account.findFirstOrThrow({where:{userId:user.id}});
 assert.notEqual(account.password,password); assert.ok(account.password);
 response=await call('/sign-in/email',{email,password}); assert.equal(response.status,403);
 const verificationURL=mails.find(m=>m.to===email)!.text.match(/https?:\/\/\S+/)![0];
 response=await auth.handler(new Request(verificationURL)); assert.ok([200,302].includes(response.status));
 user=await db.user.findUniqueOrThrow({where:{email}}); assert.equal(user.emailVerified,true);
 assert.ok(await db.customer.findUnique({where:{authUserId:user.id}}));
 response=await call('/sign-in/email',{email,password}); assert.equal(response.status,200,await response.text());
 const cookie=response.headers.get('set-cookie')!.split(';')[0];
 assert.equal((await auth.api.getSession({headers:new Headers({cookie})}))?.user.id,user.id);
 await auth.api.requestPasswordReset({body:{email,redirectTo:baseURL+'/restablecer'}});
 const resetURL=mails.filter(m=>m.to===email).at(-1)!.text.match(/https?:\/\/\S+/)![0];
 response=await auth.handler(new Request(resetURL));
 const target=response.headers.get('location')!; assert.ok(target);
 const token=new URL(target,baseURL).searchParams.get('token')!; assert.ok(token);
 response=await call('/reset-password',{token,newPassword:password+' nueva'}); assert.equal(response.status,200,await response.text());
 assert.equal(await auth.api.getSession({headers:new Headers({cookie})}),null);
 response=await call('/reset-password',{token,newPassword:password}); assert.notEqual(response.status,200);
 response=await call('/sign-in/email',{email,password:password+' nueva'}); assert.equal(response.status,200,await response.text());
 const freshCookie=response.headers.get('set-cookie')!.split(';')[0];
 response=await call('/sign-out',{},freshCookie); assert.equal(response.status,200);
 assert.equal(await auth.api.getSession({headers:new Headers({cookie:freshCookie})}),null);
});
