test('códigos únicos y cortos; compartir exige tutor y aceptación del correo invitado',async()=>{
 const owner=await db.user.create({data:{...person('owner@example.test'),emailVerified:true}});
 const other=await db.user.create({data:{...person('other@example.test'),emailVerified:true}});
 const stranger=await db.user.create({data:{...person('stranger@example.test'),emailVerified:true}});
 const contact=await syncCustomer(db,owner.id);
 const pet=await createManagedPet(db,{name:'Milo',species:'DOG',customerIds:[contact.id]});
 assert.match(pet.code,/^M-[A-Z2-9]{6}$/);
 let attempt=0;
 const second=await createManagedPet(db,{name:'Luna',species:'CAT',customerIds:[contact.id]},()=>attempt++===0 ? pet.code:'M-ZZZZZZ');
 assert.notEqual(second.code,pet.code);
 await assert.rejects(createPetInvitation(db,stranger.id,pet.id,other.email));
 const invite=await createPetInvitation(db,owner.id,pet.id,other.email);
 assert.notEqual(invite.invitation.tokenHash,invite.token); assert.equal(invite.invitation.tokenHash,tokenDigest(invite.token));
 await assert.rejects(acceptPetInvitation(db,invite.token,stranger.id));
 await acceptPetInvitation(db,invite.token,other.id);
 assert.equal(await db.petGuardian.count({where:{petId:pet.id}}),2);
 assert.equal(await db.petGuardian.count({where:{customerId:contact.id}}),2);
 await assert.rejects(acceptPetInvitation(db,invite.token,other.id));
 const expired=await createPetInvitation(db,owner.id,second.id,other.email);
 await db.petInvitation.update({where:{id:expired.invitation.id},data:{expiresAt:new Date(0)}});
 await assert.rejects(acceptPetInvitation(db,expired.token,other.id));
 const revoked=await createPetInvitation(db,owner.id,second.id,other.email);
 await db.petInvitation.update({where:{id:revoked.invitation.id},data:{revokedAt:new Date()}});
 await assert.rejects(acceptPetInvitation(db,revoked.token,other.id));
 const removed=await createPetInvitation(db,owner.id,second.id,other.email);
 await db.petGuardian.delete({where:{petId_customerId:{petId:second.id,customerId:contact.id}}});
 await assert.rejects(acceptPetInvitation(db,removed.token,other.id));
});
